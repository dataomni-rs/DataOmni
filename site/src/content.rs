#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Locale {
  En,
  Zh,
}

impl Locale {
  pub fn html_lang(self) -> &'static str {
    match self {
      Self::En => "en",
      Self::Zh => "zh-CN",
    }
  }

  pub fn canonical_path(self) -> &'static str {
    match self {
      Self::En => "/",
      Self::Zh => "/zh/",
    }
  }

  pub fn alternate_path(self) -> &'static str {
    match self {
      Self::En => "/zh/",
      Self::Zh => "/",
    }
  }

  pub fn alternate_label(self) -> &'static str {
    match self {
      Self::En => "中文",
      Self::Zh => "EN",
    }
  }
}

